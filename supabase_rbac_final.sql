-- RBAC FULL SETUP
-- This script implements a complete Role-Based Access Control system

-- 1. Extend roles in profiles if needed (check constraint)
DO $$ 
BEGIN
    ALTER TABLE public.profiles DROP CONSTRAINT IF EXISTS profiles_role_check;
    ALTER TABLE public.profiles ADD CONSTRAINT profiles_role_check CHECK (role IN ('SECRETARIA', 'FONO', 'DONA', 'admin', 'OWNER', 'PROFISSIONAL'));
END $$;

-- 2. Create role_permissions table
CREATE TABLE IF NOT EXISTS public.role_permissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role TEXT NOT NULL,
  resource TEXT NOT NULL,
  can_view BOOLEAN DEFAULT FALSE,
  can_create BOOLEAN DEFAULT FALSE,
  can_update BOOLEAN DEFAULT FALSE,
  can_delete BOOLEAN DEFAULT FALSE,
  scope TEXT DEFAULT 'all', -- 'all' or 'own'
  UNIQUE(role, resource)
);

-- Enable RLS on role_permissions
ALTER TABLE public.role_permissions ENABLE ROW LEVEL SECURITY;

-- 3. has_permission function
CREATE OR REPLACE FUNCTION public.has_permission(
  p_resource TEXT,
  p_action TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_role TEXT;
  v_has_perm BOOLEAN;
BEGIN
  -- Get user role
  SELECT role INTO v_role FROM public.profiles WHERE id = auth.uid();
  
  -- Admin/DONA/OWNER/SECRETARIA bypass
  IF v_role IN ('admin', 'DONA', 'OWNER', 'SECRETARIA') THEN
    RETURN TRUE;
  END IF;

  -- Check specific permission
  SELECT 
    CASE 
      WHEN p_action = 'view' THEN can_view
      WHEN p_action = 'create' THEN can_create
      WHEN p_action = 'update' THEN can_update
      WHEN p_action = 'delete' THEN can_delete
      ELSE FALSE
    END INTO v_has_perm
  FROM public.role_permissions
  WHERE role = v_role AND resource = p_resource;

  RETURN COALESCE(v_has_perm, FALSE);
END;
$$;

-- 4. Seed Default Permissions
INSERT INTO public.role_permissions (role, resource, can_view, can_create, can_update, can_delete, scope)
VALUES 
  ('SECRETARIA', 'appointments', true, true, true, true, 'all'),
  ('SECRETARIA', 'patients', true, true, true, true, 'all'),
  ('SECRETARIA', 'settings', true, true, true, true, 'all'),
  ('SECRETARIA', 'rbac', true, true, true, true, 'all'),
  ('SECRETARIA', 'profiles', true, true, true, true, 'all'),
  ('PROFISSIONAL', 'appointments', true, false, true, false, 'own'),
  ('PROFISSIONAL', 'patients', true, false, false, false, 'own'),
  ('FONO', 'appointments', true, false, true, false, 'own'), -- Legacy role support
  ('FONO', 'patients', true, false, false, false, 'own')  -- Legacy role support
ON CONFLICT (role, resource) DO UPDATE SET
  can_view = EXCLUDED.can_view,
  can_create = EXCLUDED.can_create,
  can_update = EXCLUDED.can_update,
  can_delete = EXCLUDED.can_delete,
  scope = EXCLUDED.scope;

-- 5. Apply RLS Policies to all tables

-- Profiles
DROP POLICY IF EXISTS "Has perms to view profiles" ON public.profiles;
CREATE POLICY "Has perms to view profiles" ON public.profiles
  FOR SELECT USING (has_permission('profiles', 'view') OR auth.uid() = id);

-- Appointments
DROP POLICY IF EXISTS "Has perms to all appointments" ON public.appointments;
CREATE POLICY "Has perms to all appointments" ON public.appointments
  FOR ALL USING (
    has_permission('appointments', 'view') AND (
      (SELECT scope FROM role_permissions WHERE role = (SELECT role FROM profiles WHERE id = auth.uid()) AND resource = 'appointments') = 'all'
      OR fono_id = auth.uid()
    )
  );

-- Patients
DROP POLICY IF EXISTS "Has perms to all patients" ON public.patients;
CREATE POLICY "Has perms to all patients" ON public.patients
  FOR ALL USING (
    has_permission('patients', 'view') AND (
      (SELECT scope FROM role_permissions WHERE role = (SELECT role FROM profiles WHERE id = auth.uid()) AND resource = 'patients') = 'all'
      OR fono_id = auth.uid()
    )
  );

-- Appointment Types
DROP POLICY IF EXISTS "Has perms to view appointment types" ON public.appointment_types;
CREATE POLICY "Has perms to view appointment types" ON public.appointment_types
  FOR SELECT USING (true); -- Everyone can view

DROP POLICY IF EXISTS "Has perms to manage appointment types" ON public.appointment_types;
CREATE POLICY "Has perms to manage appointment types" ON public.appointment_types
  FOR ALL USING (has_permission('settings', 'update'));

-- Settings
DROP POLICY IF EXISTS "Has perms to manage settings" ON public.settings;
CREATE POLICY "Has perms to manage settings" ON public.settings
  FOR ALL USING (has_permission('settings', 'update'));

-- Role Permissions (Self management)
DROP POLICY IF EXISTS "Only admin can manage perms" ON public.role_permissions;
CREATE POLICY "Only admin can manage perms" ON public.role_permissions
  FOR ALL USING (has_permission('rbac', 'view'));
